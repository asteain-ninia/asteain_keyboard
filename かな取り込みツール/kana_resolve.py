def _row(*items):
    """あ段〜お段の 5 つを (ラベル, コードポイント) に整える"""
    out = []
    for it in items:
        if it is None:
            out.append(None)  # その段は存在しない
        elif isinstance(it, tuple):
            out.append(it)
        else:
            out.append((it, ord(it)))
    return out


