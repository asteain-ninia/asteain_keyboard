def label_for_pos(section, col, dan, script="katakana"):
    """(セクション名, 列, 段) → (ラベル, コードポイント)。該当なしは (None, None)"""
    tables, col_to_row, extra, singles = SCRIPTS[script]
    key = (section, col, dan)
    if key in extra:
        return singles[extra[key]]
    row_name = col_to_row.get(section, {}).get(col)
    if not row_name:
        return None, None
    table = tables.get(section)
    if not table or row_name not in table:
        return None, None
    cell = table[row_name][dan] if dan < len(table[row_name]) else None
    return cell if cell else (None, None)


def label_for_cell(col, row, script="katakana"):
    """升目の (列, 行) → (ラベル, コードポイント)。セクションの位置は既定値を使う。"""
    for section, base in SECTION_SPANS:
        if base <= row <= base + 4:
            return label_for_pos(section, col, row - base, script)
    return None, None


def cell_of(bbox):
    """絶対座標の bbox → ガイドの (列, 行)。中心で判定する。"""
    cx = (bbox[0] + bbox[2]) / 2
    cy = (bbox[1] + bbox[3]) / 2
    return int((cx - GRID_X) // CELL_W), int((cy - GRID_Y) // CELL_H)


def label_for(section, row_name, dan):
    """(セクション名, 行名, 段0-4) → (ラベル, コードポイント)。該当なしは (None, None)"""
    if row_name in SINGLES:
        return SINGLES[row_name]
    table = SECTION_TABLES.get(section)
    if not table or row_name not in table:
        return None, None
    row = table[row_name]
    if not 0 <= dan < len(row) or row[dan] is None:
        return None, None
    return row[dan]


def union_all(pieces):
    total = None
    for p in pieces:
        total = p if total is None else op(total, p, PathOp.UNION)
    return total


def svg_d(path, dx, dy):
    pen = SVGPathPen(None, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
    path.draw(TransformPen(pen, Transform(1, 0, 0, 1, dx, dy)))
    return pen.getCommands()
